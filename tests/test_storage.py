# --- POST /api/evaluations/{id}/feedback ---

def submit(client):
    response = client.post(
        "/api/evaluate", data={"concept_id": "1"},
        files={"file": ("clip.wav", b"fake audio", "audio/wav")},
    )
    assert response.status_code == 200, response.text
    return response.json()


def stored(session_factory, eval_id):
    db = session_factory()
    try:
        return db.query(Evaluation).filter(Evaluation.id == eval_id).one()
    finally:
        db.close()


def test_feedback_endpoint_replaces_rule_based_feedback(client, session_factory):
    attempt = submit(client)
    response = client.post(f"/api/evaluations/{attempt['id']}/feedback")
    assert response.status_code == 200
    body = response.json()
    assert (body["feedback"], body["feedback_source"], body["llm_model"], body["feedback_status"]) == (
        "LLM feedback", "llm", "gemini-test-model", "done")
    assert body["feedback_seconds"] is not None and body["feedback_seconds"] >= 0
    row = stored(session_factory, attempt["id"])
    assert (row.feedback_source, row.feedback_status) == ("llm", "done")
    # Scores and grade are not changed by the feedback request
    for field in ["final_score", "understanding_score", "fluency_score", "understanding_grade"]:
        assert body[field] == attempt[field]


def test_feedback_endpoint_is_idempotent_once_done(client):
    attempt = submit(client)
    client.post(f"/api/evaluations/{attempt['id']}/feedback")
    second = client.post(f"/api/evaluations/{attempt['id']}/feedback").json()
    assert LLM["calls"] == 1
    assert second["feedback_source"] == "llm"


def test_feedback_endpoint_does_not_call_twice_while_generating(client, session_factory):
    attempt = submit(client)
    db = session_factory()
    row = db.query(Evaluation).filter(Evaluation.id == attempt["id"]).one()
    row.feedback_status, row.feedback_started_at = "generating", datetime.utcnow()
    db.commit()
    db.close()
    body = client.post(f"/api/evaluations/{attempt['id']}/feedback").json()
    assert LLM["calls"] == 0
    assert body["feedback_status"] == "generating"
    assert body["feedback_source"] == "rule-based"


def test_feedback_endpoint_reclaims_stale_generation(client, session_factory):
    attempt = submit(client)
    db = session_factory()
    row = db.query(Evaluation).filter(Evaluation.id == attempt["id"]).one()
    row.feedback_status = "generating"
    row.feedback_started_at = datetime.utcnow() - timedelta(seconds=main.STALE_FEEDBACK_SECONDS + 1)
    db.commit()
    db.close()
    body = client.post(f"/api/evaluations/{attempt['id']}/feedback").json()
    assert LLM["calls"] == 1
    assert body["feedback_status"] == "done"


def test_feedback_endpoint_failure_keeps_rule_based(client, session_factory):
    attempt = submit(client)
    LLM["fail"] = True
    body = client.post(f"/api/evaluations/{attempt['id']}/feedback").json()
    assert (body["feedback_source"], body["feedback_status"], body["llm_model"]) == ("rule-based", "failed", None)
    assert body["feedback"] == attempt["feedback"]
    assert body["feedback_seconds"] is not None
    # A later request may try again
    LLM["fail"] = False
    assert client.post(f"/api/evaluations/{attempt['id']}/feedback").json()["feedback_status"] == "done"


def test_feedback_endpoint_without_key(client):
    LLM["configured"] = False
